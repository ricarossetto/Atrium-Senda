const RUN_TIMEOUT_MS = Number(process.env.ATRIUM_TEST_TIMEOUT_MS) || 300_000;

async function runCommand(args, description) {
  const start = Date.now();
  return new Promise((resolve, reject) => {
    let settled = false;
    const finish = (error, value) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      if (error) reject(error); else resolve(value);
    };
    const child = spawn(process.execPath, args, { cwd: ROOT, stdio: 'inherit' });
    const timer = setTimeout(() => {
      child.kill('SIGTERM');
      setTimeout(() => child.kill('SIGKILL'), 5_000).unref?.();
      const duration = ((Date.now() - start) / 1000).toFixed(2);
      finish(new Error(`${description} excedeu ${RUN_TIMEOUT_MS / 1000}s sem terminar (${duration}s); processo encerrado.`));
    }, RUN_TIMEOUT_MS);
    child.on('error', error => finish(error));
    child.on('exit', code => {
      const duration = ((Date.now() - start) / 1000).toFixed(2);
      if (code === 0) finish(null, duration);
      else finish(new Error(`${description} falhou com código ${code} (${duration}s)`));
    });
  });
}

